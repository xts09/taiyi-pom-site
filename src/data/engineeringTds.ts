export const createEngineeringTdsSlug = (
  document: Pick<EngineeringTdsDocument, "grade" | "family" | "category">
) =>
  `${document.grade}-${document.family}-${document.category}`
    .trim()
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/\//g, " ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

